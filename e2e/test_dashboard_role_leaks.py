"""Live Dashboard role-leak journey (D-MIS-8): Today's Mission reads are founder + team member only.

One founder workspace with a team member, a mentor and a business consultant. Proves, against the
running app, what each role gets from `GET /dashboard/summary` (`mission` / `mission_status`),
`GET /search` (mission tasks, the Mission and Assessment pages) and the notification feed
(`mission.completed`, `dashboard.briefing.ready`). Every body is captured to
`e2e/_captures/dashboard_role_leaks/*.json`, the verbatim source for
`docs/fe-integration-guide-dashboard-role-leaks.md`.

The briefing is generated by draining the worker in-process (LLM_PROVIDER=stub); the notifications
registry is registered in this process too, because `dashboard.briefing.ready` is published here
(see `test_notifications_scheduler._tick_and_drain`).
"""

from datetime import date

import httpx

_LOW_ANSWERS = {
    "product_stage": "idea",
    "market_clarity": 3,
    "market_research": "none",
    "has_revenue": "no",
    "runway_confidence": 3,
    "incorporated": "no",
    "team_size": "solo",
    "team_confidence": 3,
}
G = "dashboard_role_leaks"
S = "/api/v1/dashboard/summary"


def _auth(token: str) -> dict:
    return {"Authorization": f"Bearer {token}"}


def _join(c, wh, ws, role, unique_email, mailbox):
    """Invite `role` to the workspace and accept as a freshly verified user."""
    email = unique_email(role)
    r = c.post(
        "/api/v1/team/invitations", headers=wh, json={"invites": [{"email": email, "role": role}]}
    )
    assert r.status_code == 200, r.text
    token = mailbox.latest_token_for(email, subject_contains="invited")
    pw = "Member-" + email.split("@")[0][-8:] + "-9"
    c.post("/api/v1/auth/signup", json={"email": email, "password": pw})
    c.post(
        "/api/v1/auth/verify",
        json={"token": mailbox.latest_token_for(email, subject_contains="Verify")},
    )
    access = c.post("/api/v1/auth/login", json={"email": email, "password": pw}).json()["data"][
        "access_token"
    ]
    auth = _auth(access)
    acc = c.post("/api/v1/invitations/accept", headers=auth, json={"token": token})
    assert acc.status_code == 200, acc.text
    return {**auth, "X-Workspace-Id": ws}


def _complete_assessment(c, wh) -> None:
    aid = c.post("/api/v1/assessments", headers=wh).json()["data"]["assessment_id"]
    while True:
        nq = c.get(f"/api/v1/assessments/{aid}/next-question", headers=wh).json()["data"][
            "next_question"
        ]
        if nq is None:
            break
        r = c.post(
            f"/api/v1/assessments/{aid}/answers",
            headers=wh,
            json={"question_key": nq["key"], "value": _LOW_ANSWERS[nq["key"]]},
        )
        assert r.status_code == 200, r.text
    assert c.post(f"/api/v1/assessments/{aid}/complete", headers=wh).status_code == 200


def _drain() -> None:
    from app.db.session import SessionLocal
    from app.services.notifications.registry import register as register_notifications
    from app.worker import runner
    from app.worker.handlers import ai as _ai  # noqa: F401  (registers ai.dashboard.briefing)

    register_notifications()
    db = SessionLocal()
    try:
        for _ in range(500):
            if runner.run_once(db) == 0:
                break
    finally:
        db.close()


def _types(c, h) -> list[str]:
    r = c.get("/api/v1/notifications", headers=h)
    assert r.status_code == 200, r.text
    return [n["type"] for n in r.json()["data"]["notifications"]]


def _search(c, h, q):
    r = c.get("/api/v1/search", params={"q": q}, headers=h)
    assert r.status_code == 200, r.text
    return r, r.json()["data"]["results"]


def test_dashboard_role_leaks_journey(base_url, make_verified_user, unique_email, mailbox, capture):
    with httpx.Client(base_url=base_url, timeout=15.0) as c:
        u = make_verified_user(c)
        auth = _auth(c.post("/api/v1/auth/login", json=u).json()["data"]["access_token"])
        c.get("/api/v1/onboarding/state", headers=auth)
        c.patch("/api/v1/onboarding/state", headers=auth, json={"step": 1, "full_name": "Ada F"})
        c.patch("/api/v1/onboarding/state", headers=auth, json={"step": 2, "name": "NovaPay"})
        c.patch(
            "/api/v1/onboarding/state",
            headers=auth,
            json={"step": 3, "industry": "Fintech", "business_model": "b2b", "stage": "validation"},
        )
        c.patch("/api/v1/onboarding/state", headers=auth, json={"step": 4, "goals": ["Grow"]})
        assert c.post("/api/v1/onboarding/complete", headers=auth).status_code == 200
        ws = c.get("/api/v1/auth/me", headers=auth).json()["data"]["active_workspace_id"]
        wh = {**auth, "X-Workspace-Id": ws}

        team = _join(c, wh, ws, "team_member", unique_email, mailbox)
        mentor = _join(c, wh, ws, "mentor", unique_email, mailbox)
        consultant = _join(c, wh, ws, "business_consultant", unique_email, mailbox)

        # Weekend guard (see e2e/test_dashboard_ai_briefing.py): before the first summary call.
        if date.today().weekday() in (5, 6):
            wk = c.patch("/api/v1/missions/settings", headers=wh, json={"weekend_missions": True})
            assert wk.status_code == 200, wk.text

        _complete_assessment(c, wh)  # opens the briefing gate

        # 1. Mentor FIRST: the old code lazily generated (wrote) the mission for any viewer.
        #    Now the mentor gets mission null and nothing is generated for them.
        m1 = c.get(S, headers=mentor)
        assert m1.status_code == 200, m1.text
        d = m1.json()["data"]
        assert d["mission"] is None and d["mission_status"] == "restricted"
        capture(G, "summary_mentor", m1)
        mc = c.get(S, headers=consultant)
        assert mc.json()["data"]["mission"] is None
        assert mc.json()["data"]["mission_status"] == "restricted"
        capture(G, "summary_business_consultant", mc)
        gone = c.get("/api/v1/missions/today", headers=mentor)
        assert gone.status_code == 403
        capture(G, "missions_today_mentor_403", gone)

        # 2. Founder + team member get the real mission.
        fs = c.get(S, headers=wh)
        fd = fs.json()["data"]
        assert fd["mission_status"] == "ok" and fd["mission"]["tasks"]
        capture(G, "summary_founder", fs)
        ts = c.get(S, headers=team)
        assert ts.json()["data"]["mission_status"] == "ok" and ts.json()["data"]["mission"]["tasks"]
        capture(G, "summary_team_member", ts)

        # The mentor still sees nothing of it after the founder generated it.
        m2 = c.get(S, headers=mentor)
        assert m2.json()["data"]["mission"] is None
        assert fd["mission"]["tasks"][0]["title"] not in m2.text

        # 3. Search: the mission task is found by the founder/team, never by the mentor.
        title = fd["mission"]["tasks"][0]["title"]
        needle = title[:12]
        r_f, hits_f = _search(c, wh, needle)
        assert any(h["type"] == "mission_task" for h in hits_f)
        capture(G, "search_mission_task_founder", r_f)
        r_m, hits_m = _search(c, mentor, needle)
        assert not any(h["type"] == "mission_task" for h in hits_m)
        capture(G, "search_mission_task_mentor", r_m)

        r_pm, hits_pm = _search(c, mentor, "mission")
        assert "Today's Mission" not in {h["title"] for h in hits_pm}
        capture(G, "search_mission_page_mentor", r_pm)
        r_pf, hits_pf = _search(c, wh, "mission")
        assert "Today's Mission" in {h["title"] for h in hits_pf}
        capture(G, "search_mission_page_founder", r_pf)

        # 4. Search: Assessment page for the team member (was founder-only), not the mentor.
        r_at, hits_at = _search(c, team, "assessment")
        assert [h["href"] for h in hits_at if h["type"] == "page"] == ["/assessment"]
        capture(G, "search_assessment_team_member", r_at)
        r_am, hits_am = _search(c, mentor, "assessment")
        assert hits_am == []
        capture(G, "search_assessment_mentor", r_am)

        # 5. Briefing: generate it, then check who is told (briefing prose stays restricted).
        assert c.get(S, headers=wh).json()["data"]["briefing"]["status"] == "generating"
        _drain()
        ready = c.get(S, headers=wh)
        assert ready.json()["data"]["briefing"]["status"] == "ready"
        capture(G, "summary_founder_briefing_ready", ready)
        ment = c.get(S, headers=mentor)
        assert ment.json()["data"]["briefing"]["status"] == "restricted"
        assert "briefing.ready" not in " ".join(_types(c, mentor))
        assert "dashboard.briefing.ready" in _types(c, wh)
        assert "dashboard.briefing.ready" in _types(c, team)
        assert "dashboard.briefing.ready" not in _types(c, consultant)

        # 6. Complete every task as the founder -> mission.completed reaches the team member only.
        tasks = c.get(S, headers=wh).json()["data"]["mission"]["tasks"]
        for t in tasks:
            done = c.patch(
                f"/api/v1/missions/tasks/{t['id']}", headers=wh, json={"action": "complete"}
            )
            assert done.status_code == 200, done.text
        assert "mission.completed" in _types(c, team)
        assert "mission.completed" not in _types(c, mentor)
        assert "mission.completed" not in _types(c, consultant)
        capture(G, "notifications_team_member", c.get("/api/v1/notifications", headers=team))
        capture(G, "notifications_mentor", c.get("/api/v1/notifications", headers=mentor))
